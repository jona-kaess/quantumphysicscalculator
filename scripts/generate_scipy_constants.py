"""Generate the browser's constants catalog from the installed SciPy CODATA data."""
import ast
import json
import re
from pathlib import Path
from scipy import __version__ as scipy_version, constants as c

ZERO = (0,) * 7
BASE = {
    'm': (1, (1,0,0,0,0,0,0)), 'kg': (1, (0,1,0,0,0,0,0)),
    's': (1, (0,0,1,0,0,0,0)), 'A': (1, (0,0,0,1,0,0,0)),
    'K': (1, (0,0,0,0,1,0,0)), 'mol': (1, (0,0,0,0,0,1,0)),
    'Hz': (1, (0,0,-1,0,0,0,0)), 'J': (1, (2,1,-2,0,0,0,0)),
    'C': (1, (0,0,1,1,0,0,0)), 'N': (1, (1,1,-2,0,0,0,0)),
    'T': (1, (0,1,-2,-1,0,0,0)), 'V': (1, (2,1,-3,-1,0,0,0)),
    'W': (1, (2,1,-3,0,0,0,0)), 'Pa': (1, (-1,1,-2,0,0,0,0)),
    'ohm': (1, (2,1,-3,-2,0,0,0)), 'F': (1, (-2,-1,4,2,0,0,0)),
    'H': (1, (2,1,-2,-2,0,0,0)), 'S': (1, (-2,-1,3,2,0,0,0)),
    'Wb': (1, (2,1,-2,-1,0,0,0)), 'lm': (1, (0,0,0,0,0,0,1)),
    'sr': (1, ZERO), 'u': (c.physical_constants['atomic mass constant'][0], (0,1,0,0,0,0,0)),
    'E_h': (c.physical_constants['Hartree energy'][0], (2,1,-2,0,0,0,0)),
    'eV': (c.e, (2,1,-2,0,0,0,0)), 'MeV': (1e6*c.e, (2,1,-2,0,0,0,0)),
    'GeV': (1e9*c.e, (2,1,-2,0,0,0,0)), 'MHz': (1e6, (0,0,-1,0,0,0,0)),
    'fm': (1e-15, (1,0,0,0,0,0,0)), 'c': (c.c, (1,0,-1,0,0,0,0)),
    # 1990 conventional ampere = (K_J/K_J-90)/(R_K/R_K-90) SI ampere.
    'C_90': ((c.physical_constants['Josephson constant'][0] / c.physical_constants['conventional value of Josephson constant'][0]) /
             (c.physical_constants['von Klitzing constant'][0] / c.physical_constants['conventional value of von Klitzing constant'][0]), (0,0,1,1,0,0,0)),
}
def calculate(node):
    if isinstance(node, ast.Name): return BASE[node.id]
    if isinstance(node, ast.Constant): return float(node.value), ZERO
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
        value, dim = calculate(node.operand)
        if dim != ZERO: raise ValueError('Dimensional exponent')
        return -value, ZERO
    if isinstance(node, ast.BinOp):
        a, ad = calculate(node.left); b, bd = calculate(node.right)
        if isinstance(node.op, ast.Mult): return a*b, tuple(x+y for x,y in zip(ad,bd))
        if isinstance(node.op, ast.Div): return a/b, tuple(x-y for x,y in zip(ad,bd))
        if isinstance(node.op, ast.Pow) and bd == ZERO: return a**b, tuple(x*b for x in ad)
    raise ValueError(ast.dump(node))

def unit_value(text):
    if not text: return 1, ZERO
    expression = re.sub(r'\s+', '*', text.strip()).replace('^','**')
    return calculate(ast.parse(expression, mode='eval').body)

def main():
    data = {}
    for name, (value, units, uncertainty) in c.physical_constants.items():
        factor, dim = unit_value(units)
        symbol = 'scipy_' + re.sub(r'[^A-Za-z0-9]+', '_', name).strip('_')
        if symbol in data: raise ValueError(f'Duplicate constant symbol: {symbol}')
        data[symbol] = {'name':name, 'value':value*factor, 'dim':dim, 'unit':units,
                        'sourceValue':value, 'uncertainty':uncertainty, 'source':'SciPy CODATA 2018'}
    output = '/* Generated by scripts/generate_scipy_constants.py; SciPy ' + scipy_version + '. */\n'
    output += '(function(root,data){if(typeof module === "object" && module.exports) module.exports=data; else root.ScipyConstants=data;})(typeof globalThis !== "undefined" ? globalThis : this,\n'
    output += json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ');\n'
    Path('app/static/js/scipy-constants.js').write_text(output, encoding='utf-8')
    print(f'Generated {len(data)} constants from SciPy {scipy_version}')
if __name__ == '__main__': main()
